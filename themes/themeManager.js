// Keep the legacy image fields working while exposing explicit profile assets
// for each theme. Replace the URLs in the profile blocks with your own assets.
for (const theme of Object.values(themes)) {
  theme.profile ||= {};
  theme.profile.avatar ||= theme.images?.thumbnail || theme.images?.main || '';
  theme.profile.superBanner ||= theme.images?.superBanner || theme.images?.main || '';
  theme.profile.banner ||= theme.images?.banner || theme.profile.superBanner || '';
  theme.images ||= {};
  theme.images.main = theme.profile.superBanner || theme.images.main || '';
  theme.images.thumbnail = theme.profile.avatar || theme.images.thumbnail || '';
  theme.images.superBanner = theme.profile.superBanner || theme.images.superBanner || '';
  theme.images.banner = theme.profile.banner || theme.images.banner || '';
}

import GuildConfig from '../models/guildConfig.js';
const themeCache = new Map();
const DEFAULT_THEME_NAME = 'black';

export { themes };
export default {
  themes,
  async getTheme(guildId) {
    // All control panels use the original black theme.
    // Legacy per-guild theme values are intentionally ignored.
    if (guildId) themeCache.set(guildId, DEFAULT_THEME_NAME);
    return themes[DEFAULT_THEME_NAME];
  },

  async setTheme(guildId, theme) {
    if (!themes[theme]) {
      throw new Error(`Unknown theme: ${theme}`);
    }

    try {
      await GuildConfig.findOneAndUpdate(
        { guildId },
        { theme },
        { upsert: true, new: true },
      );
    } catch {
      // Keep the in-memory selection when persistent storage is unavailable.
    }
    themeCache.set(guildId, theme);
  },

  async applyBotProfile(client, theme) {
    const profile = theme?.profile || {};
    const updates = [
      ['avatar', profile.avatar, () => client.user.setAvatar(profile.avatar)],
      ['banner', profile.banner, () => client.user.setBanner(profile.banner)],
    ];
    const updated = [];
    const failed = [];

    for (const [asset, value, update] of updates) {
      if (!value) continue;
      try {
        await update();
        updated.push(asset);
      } catch (error) {
        failed.push({ asset, message: error.message });
      }
    }

    return { updated, failed };
  },

  getCachedTheme(guildId) {
    if (guildId) themeCache.set(guildId, DEFAULT_THEME_NAME);
    return themes[DEFAULT_THEME_NAME];
  },

  applyThemeToEmbed(embed, theme) {
    if (!theme) return embed;
    embed.setColor(theme.color);
    if (theme.footer) embed.setFooter({ text: theme.footer });
    return embed;
  },

  async getEmoji(guildId, type) {
    const theme = await this.getTheme(guildId);
    return theme.emojis[type] || '';
  },

  async getImage(guildId, type) {
    const theme = await this.getTheme(guildId);
    return theme.images[type] || '';
  },

  async getBanner(guildId) {
    const theme = await this.getTheme(guildId);
    return theme.profile?.banner || theme.images?.banner || theme.banner || '';
  },

  getRGBColor(colorInt) {
    const hex = colorInt || 0x010101;
    const r = (hex >> 16) & 0xFF;
    const g = (hex >> 8) & 0xFF;
    const b = hex & 0xFF;
    return [r, g, b];
  }
};